import assert from 'node:assert/strict';
import {createWishStore,WISH_KEY} from './hope-wish-store.js';
const values=new Map(),storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
values.set('hopeIslandWishes',JSON.stringify([{id:'legacy',text:'舊願望',islandId:'island.imaging',completed:true}]));
const original=values.get('hopeIslandWishes'),store=createWishStore(storage);
assert.equal(store.wishes[0].island,1);assert.equal(store.wishes[0].status,'archived');
assert.equal(store.add('  ',1,'empty'),null);
assert(store.add('<script>文字安全保留</script>',3,'new'));
assert.equal(store.add('重複',1,'new'),null);
assert(store.complete('new'));assert.equal(store.complete('new'),false);
assert.equal(store.wishes[1].status,'completed');
assert(store.archive('new'));assert.equal(store.wishes[1].status,'archived');
assert.equal(createWishStore(storage).wishes[1].status,'archived');
assert.equal(values.get('hopeIslandWishes'),original,'Legacy storage is never overwritten.');
const failing=createWishStore({getItem:()=>null,setItem:()=>{throw Error('quota');}});
assert(failing.add('暫存願望',0,'temp'));assert.equal(failing.persistent,false);
values.set(WISH_KEY,JSON.stringify([{id:'interrupted',text:'完成中重新載入',island:1,status:'completed'}]));
assert.equal(createWishStore(storage).wishes[0].status,'archived','Reload must not replay completed meteors.');
console.log('PASS: legacy import, wish lifecycle, persistence, duplicate completion and storage failure.');
